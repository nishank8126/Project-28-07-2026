const AciColorTable& AciColorTable::Instance() {
    static AciColorTable s_instance;
    return s_instance;
}

Rgb AciColorTable::Lookup(int aci) const {
    if (aci >= 1 && aci <= 255) return m_table[aci];
    return {255, 255, 255};
}

std::tuple<float, float, float> AciColorTable::LookupNormalized(int aci) const {
    auto [r, g, b] = Lookup(aci);
    return {r / 255.0f, g / 255.0f, b / 255.0f};
}

Rgb AciColorTable::TrueColorToRgb(uint32_t tc) const {
    return {
        static_cast<uint8_t>((tc >> 16) & 0xFF),
        static_cast<uint8_t>((tc >> 8) & 0xFF),
        static_cast<uint8_t>(tc & 0xFF)
    };
}

